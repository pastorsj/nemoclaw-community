# Regenerate the cross-language contracts from the API's Pydantic models.
#
#   scripts/gen-contracts.sh           write contracts/schemas and ui/src/generated
#
# Needs uv and Node.js (for npx).
set -euo pipefail

# Pinned so the generated TypeScript is reproducible.
readonly JSON2TS=json-schema-to-typescript@16.0.0
readonly PRETTIER=prettier@3.9.9
readonly BANNER='// SPDX-FileCopyrightText: Copyright (c) 2026, NVIDIA CORPORATION & AFFILIATES. All rights reserved.
// SPDX-License-Identifier: Apache-2.0

/* Generated by scripts/gen-contracts.sh from contracts/. Do not edit. */'

root="$(cd "$(dirname "$0")/.." && pwd)"

[ $# -eq 0 ] || {
  echo "usage: $0" >&2
  exit 2
}

generated="$root/ui/src/generated"
rm -rf "$root/contracts/schemas" "$generated"
mkdir -p "$generated"

# Pydantic -> contracts/schemas/*.schema.json.
uv run --project "$root/api" --locked --quiet python -m demo_api.contracts "$root/contracts"

# JSON Schema -> TypeScript, plus the tool registry as a typed constant.
node_tool() {
  npx --yes --package "$JSON2TS" --package "$PRETTIER" -- "$@"
}
to_typescript() {
  node_tool json2ts --input "$1" --output "$2" --bannerComment "$BANNER" --maxItems=-1 --no-format
}
to_typescript "$root/contracts/schemas/execution-event.schema.json" "$generated/execution-event.ts"
to_typescript "$root/contracts/schemas/receipt.schema.json" "$generated/receipt.ts"
to_typescript "$root/contracts/schemas/benchmark.schema.json" "$generated/benchmark.ts"
to_typescript "$root/contracts/schemas/retrieval-benchmark.schema.json" "$generated/retrieval-benchmark.ts"
to_typescript "$root/contracts/schemas/pack.schema.json" "$generated/pack.ts"
to_typescript "$root/contracts/tool-registry.schema.json" "$generated/tool-registry.ts"
printf '\nexport const TOOL_REGISTRY: ToolRegistry = %s\n' "$(cat "$root/contracts/tool-registry.json")" \
  >>"$generated/tool-registry.ts"

# Format in the style of ui/.prettierrc (without its Tailwind plugin, which only sorts class names).
node_tool prettier --no-config --no-semi --single-quote --print-width 100 --trailing-comma es5 \
  --log-level warn --write "$generated"
