def _repository_policy_files() -> list[Path]:
    """Every OpenShell policy file under ``examples/``, except this tool's own files."""
    skip_dirs = {".venv", "node_modules", ".git"}
    found = []
    for dirpath, dirnames, filenames in os.walk(EXAMPLES):
        here = Path(dirpath)
        dirnames[:] = sorted(d for d in dirnames if d not in skip_dirs and (here / d).resolve() != TOOL_DIR)
        for name in sorted(filenames):
            path = here / name
            in_policies = here.name == "policies" and path.suffix in {".yaml", ".json"}
            policy_named = name.startswith("policy") and path.suffix == ".yaml"
            if in_policies or policy_named:
                found.append(path)
    return found


