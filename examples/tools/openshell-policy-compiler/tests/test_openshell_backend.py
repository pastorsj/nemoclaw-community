def _repository_policy_files() -> list[Path]:
    """Every OpenShell policy file under ``examples/``, except this tool's own files."""
    skip_dirs = {".venv", "node_modules", ".git"}
    found = []
    for dirpath, dirnames, filenames in os.walk(EXAMPLES):
        here = Path(dirpath)
        dirnames[:] = sorted(
            d for d in dirnames if d not in skip_dirs and (here / d).resolve() != TOOL_DIR
        )
        for name in sorted(filenames):
            path = here / name
            in_policies = here.name == "policies" and path.suffix in {".yaml", ".json"}
            policy_named = name.startswith("policy") and path.suffix == ".yaml"
            if in_policies or policy_named:
                found.append(path)
    return found


def _network_policy_files() -> list[Path]:
    return [p for p in _repository_policy_files() if "network_policies" in load_policy_file(p)]


REPO_POLICIES = _network_policy_files()


def _codes(access: AccessSet) -> set[str]:
    return {d.code for d in access.diagnostics}


