def test_canonicalize():
    policy = {
        "version": 1,
        "network_policies": {
            "b": {
                "endpoints": [{"port": 443, "host": "x.example.com", "rules": [], "protocol": "rest"}],
                "binaries": [{"path": "/bin/x"}],
            },
            "a": {"name": "Alpha", "endpoints": [{"host": "y.example.com", "ports": [8443, 443]}], "binaries": []},
        },
        "filesystem_policy": {},
    }
    canonical = canonicalize(policy)
    assert canonical == {
        "network_policies": {
            "a": {"endpoints": [{"host": "y.example.com", "ports": [443, 8443]}], "name": "Alpha"},
            "b": {
                "binaries": [{"path": "/bin/x"}],
                "endpoints": [{"host": "x.example.com", "ports": [443], "protocol": "rest"}],
                "name": "b",
            },
        },
        "version": 1,
    }
    assert list(canonical) == ["network_policies", "version"]
    assert list(canonical["network_policies"]) == ["a", "b"]
    assert policy["network_policies"]["b"]["endpoints"][0]["port"] == 443  # input untouched


