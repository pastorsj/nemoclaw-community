def test_lift_builds_rules_with_reasons_and_group_order():
    policy = {
        "version": 1,
        "filesystem_policy": {"read_only": ["/usr"]},
        "network_policies": {
            "zeta": {
                "name": "Zeta API",
                "endpoints": [
                    {
                        "host": "api.example.com",
                        "port": 443,
                        "protocol": "rest",
                        "enforcement": "enforce",
                        "rules": [
                            {"allow": {"method": "GET", "path": "/v1/items"}},
                            {"allow": {"method": "POST", "path": "/v1/items"}},
                        ],
                        "deny_rules": [{"method": "POST", "path": "/v1/items/admin"}],
                    },
                    {"host": "cdn.example.com", "port": 443, "protocol": "rest", "enforcement": "enforce", "access": "read-only"},
                ],
                "binaries": [{"path": "/usr/bin/curl"}],
            },
            "alpha": {"name": "alpha", "endpoints": [{"host": "x.example.com", "port": 22}], "binaries": [{"path": "/usr/bin/ssh"}]},
        },
    }
    access = lift(policy, source="p.yaml")
    assert access.group_order == ["zeta", "alpha"]
    assert access.extras == {"version": 1, "filesystem_policy": {"read_only": ["/usr"]}}
    zeta = [r for r in access.rules if r.group == "zeta"]
    assert [(r.effect, r.matcher, r.access_preset) for r in zeta] == [
        (Effect.ALLOW, Matcher(method="GET", path="/v1/items"), None),
        (Effect.ALLOW, Matcher(method="POST", path="/v1/items"), None),
        (Effect.DENY, Matcher(method="POST", path="/v1/items/admin"), None),
        (Effect.ALLOW, None, "read-only"),
    ]
    assert zeta[0].reasons == ["p.yaml#network_policies.zeta.endpoints[0]"]
    assert zeta[3].reasons == ["p.yaml#network_policies.zeta.endpoints[1]"]
    assert {r.name for r in zeta} == {"Zeta API"}
    assert zeta[0].clients == ClientSet("list", ("/usr/bin/curl",))
    assert zeta[0].endpoint == EndpointKey(
        host="api.example.com", ports=(443,), protocol=Protocol.REST, enforcement=Enforcement.ENFORCE
    )
    (alpha,) = [r for r in access.rules if r.group == "alpha"]
    assert alpha.name is None
    assert alpha.matcher is None
    assert alpha.endpoint.protocol is Protocol.L4
    assert alpha.endpoint.enforcement is Enforcement.AUDIT


